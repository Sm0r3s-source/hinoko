"""Draws the Hinoko star (16x16 pixel grid) and writes assets/hinoko.ico + hinoko.png. Needs Pillow."""
from PIL import Image, ImageDraw
STAR = """................
..............A.
....A..A......B.
....B..AC.......
.......AC...C...
.A....AAAA..A...
.B...CAAAAA.....
...AAAACAAACAA..
..BBBAACACAAA...
.....BACACA.....
......BAAA......
....A..BA....A..
..A.B..BA....B..
..B.....B.A.....
..........C.....
................""".split()
COL = {"A": (255, 255, 255, 255), "B": (0xb4, 0xbc, 0xf0, 255), "C": (0xe6, 0xe9, 0xff, 255)}
def mark(n=256):
    im = Image.new("RGBA", (n, n), (0, 0, 0, 0)); d = ImageDraw.Draw(im)
    d.rounded_rectangle([0, 0, n - 1, n - 1], radius=n * 7 // 32, fill=(0x0e, 0x12, 0x30, 255))
    c = n // 16
    for y, r in enumerate(STAR):
        for x, k in enumerate(r):
            if k in COL: d.rectangle([x * c, y * c, x * c + c - 1, y * c + c - 1], fill=COL[k])
    return im
big = mark(256)
big.save("assets/hinoko.png")
big.save("assets/hinoko.ico", sizes=[(16, 16), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
